"""manage.py build_clearance -- decide which PDMX scores may be offered, and write the list the importer reads.

    python manage.py build_clearance --pdmx-csv /path/to/PDMX.csv

Writes two files to scores/clearance/ (commit both):

  cleared_mxl.txt        one cleared score path per line. import_pdmx reads this, and refuses to run without it.
  clearance_report.json  how many scores each rule kept or removed, and the most common composer names that were
                         NOT recognised, so a person can review them and add genuine historic composers to
                         scores/clearance.py. Nothing is ever added automatically.

The rules and why they are cautious are in scores/clearance.py. Re-run this after changing them.
"""

import csv
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from scores import clearance

DEFAULT_CSV = settings.BASE_DIR / "services" / "music_src" / "PDMX.csv"
REQUIRED_COLUMNS = ("mxl", "composer_name", "license", "license_conflict", "is_original", "rating", "subset:deduplicated")
UNRECOGNISED_TO_LIST = 200


class Command(BaseCommand):
    help = "Decide which PDMX scores are safe to offer and write the cleared list and a review report."

    def add_arguments(self, parser):
        parser.add_argument("--pdmx-csv", type=Path, default=DEFAULT_CSV)
        parser.add_argument("--output-dir", type=Path, default=clearance.CLEARANCE_DIR)
        parser.add_argument(
            "--blocklist",
            type=Path,
            default=clearance.DEFAULT_BLOCKLIST,
            help="Paths removed after a complaint; kept out even when the rules would clear them.",
        )

    def handle(self, *args, **opts):
        source: Path = opts["pdmx_csv"]
        if not source.is_file():
            raise CommandError(f"PDMX.csv not found: {source}")

        blocked = clearance.load_blocked(opts["blocklist"])
        csv.field_size_limit(sys.maxsize)
        cleared: list[str] = []
        by_reason: Counter = Counter()
        unrecognised: Counter = Counter()
        considered = 0
        with open(source, newline="", encoding="utf-8") as handle:
            reader = csv.DictReader(handle)
            missing = [c for c in REQUIRED_COLUMNS if c not in (reader.fieldnames or [])]
            if missing:
                raise CommandError(f"{source} has no {', '.join(missing)} column; is it the real PDMX.csv?")
            for row in reader:
                # The importer only ever reads the deduplicated subset, so only those are decided.
                if not clearance._true(row["subset:deduplicated"]):
                    continue
                considered += 1
                verdict = clearance.assess(row)
                path = (row["mxl"] or "").strip().removeprefix("./")
                if verdict.cleared and path in blocked:
                    verdict = clearance.Verdict(False, "blocked after a complaint")
                by_reason[verdict.reason] += 1
                if verdict.cleared and path and path not in ("N/A", "NA"):
                    cleared.append(path)
                elif verdict.reason == "composer not recognised" and _rated(row) >= 4.0:
                    unrecognised[(row["composer_name"] or "").strip()] += 1

        cleared = sorted(set(cleared))
        out: Path = opts["output_dir"]
        out.mkdir(parents=True, exist_ok=True)
        header = (
            "# Cleared PDMX scores: the only ones import_pdmx will bring in.\n"
            "# Generated by `manage.py build_clearance` (rule version "
            f"{clearance.RULE_VERSION}). Do not edit by hand; see scores/clearance.py.\n"
        )
        (out / "cleared_mxl.txt").write_text(header + "\n".join(cleared) + "\n", encoding="utf-8")
        report = {
            "rule_version": clearance.RULE_VERSION,
            "public_domain_death_year": clearance.PUBLIC_DOMAIN_DEATH_YEAR,
            "generated_from": source.name,
            "csv_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "scores_considered": considered,
            "cleared": len(cleared),
            "by_reason": dict(by_reason.most_common()),
            "unrecognised_composers": [[n, c] for n, c in unrecognised.most_common(UNRECOGNISED_TO_LIST)],
        }
        (out / "clearance_report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

        self.stdout.write(f"considered: {considered}")
        self.stdout.write(f"cleared: {len(cleared)}")
        for reason, count in by_reason.most_common():
            self.stdout.write(f"  {reason}: {count}")
        self.stdout.write(f"wrote {out / 'cleared_mxl.txt'} and {out / 'clearance_report.json'}")


def _rated(row) -> float:
    try:
        return float(row["rating"] or 0)
    except ValueError:
        return 0.0
